-- The super administrator holds everything new that is enforced; other existing roles keep exactly what they had.
-- Reserved permissions gate nothing yet, and leaving them out keeps the access token within a cookie's size.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
         CROSS JOIN permissions p
WHERE r.name = 'SUPER_ADMIN'
  AND p.code <> 'INVESTOR_PORTAL'
  AND NOT p.reserved
  AND NOT EXISTS (SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id);
